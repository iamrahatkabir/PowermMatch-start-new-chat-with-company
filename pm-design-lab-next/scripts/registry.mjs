// Writes src/lab/designs.generated.ts from src/designs/<slug>/meta.ts + one <Letter>.tsx per variant.
// Next.js has no import.meta.glob, so the lab's design list is generated. `npm run dev` runs this and
// re-runs it whenever a design folder, meta.js or variant file is added or removed.
// Run by hand with `npm run registry`.
import { existsSync, readdirSync, writeFileSync, readFileSync, watch } from 'node:fs'

const ROOT = 'src/designs'
const OUT = 'src/lab/designs.generated.ts'

export function generate() {
  const slugs = existsSync(ROOT) ? readdirSync(ROOT, { withFileTypes: true }).filter((d) => d.isDirectory() && existsSync(`${ROOT}/${d.name}/meta.ts`)).map((d) => d.name).sort() : []
  const lines = [
    "'use client'",
    '// GENERATED by scripts/registry.mjs — do not edit. Lists every design and its variants.',
    "import dynamic from 'next/dynamic'",
  ]
  const entries = []
  slugs.forEach((slug, i) => {
    lines.push(`import meta${i} from '../designs/${slug}/meta'`)
    const keys = readdirSync(`${ROOT}/${slug}`).filter((f) => /^[A-Z]\.tsx$/.test(f)).map((f) => f[0]).sort()
    const variants = keys.map((k) => `    ${k}: dynamic(() => import('../designs/${slug}/${k}'), { ssr: false }),`).join('\n')
    entries.push(`  { slug: '${slug}', meta: meta${i}, keys: ${JSON.stringify(keys)}, variants: {\n${variants}\n  } },`)
  })
  lines.push('', "import type { DesignEntry } from './types'", '', 'export const generated: DesignEntry[] = [', ...entries, ']', '')
  const next = lines.join('\n')
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== next) writeFileSync(OUT, next)
}

generate()
if (process.argv.includes('--watch')) {
  let t
  watch(ROOT, { recursive: true }, (_, file) => {
    if (!file || !/(meta\.ts|[A-Z]\.tsx)$|^[^/]+$/.test(file)) return
    clearTimeout(t)
    t = setTimeout(generate, 100)
  })
}
